# Ваша задача — определить силу гравитации между двумя сферическими объектами (obj1, obj2).

# вход
# Даны два массива:

# arr_val (массив значений), состоит из 3 элементов.
# 1-й элемент: масса объекта 1
# 2-й элемент: масса объекта 2
# 3-й элемент: расстояние между их центрами
# arr_unit (массив единиц), состоит из 3 элементов.
# 1-й элемент: единица измерения массы объекта 1
# 2-й элемент: единица измерения массы объекта 2
# 3-й элемент: единица измерения расстояния между их центрами.
# Единицы массы:

# килограмм (кг)
# грамм (г)
# миллиграмм (мг)
# микрограмм (мкг)
# фунт (lb)
# Единицами измерения расстояния являются:

# метр (м)
# сантиметр (см)
# миллиметр (мм)
# микрометр (мкм)
# футы (футы)
# Примечание
# Значение G = 6,67 × 10 −11 Н⋅кг −2 ⋅м 2

# 1 фут = 0,3048 м

# 1 фунт = 0,453592 кг

# Возвращаемое значение силы должно быть в Ньютонах (очевидно).

def solution(arr_val, arr_unit):
    # Convert masses to kg
    mass_units = {'kg': 1, 'g': 1e-3, 'mg': 1e-6, 'μg': 1e-9, 'lb': 0.453592}
    m1_kg = arr_val[0] * mass_units[arr_unit[0]]
    m2_kg = arr_val[1] * mass_units[arr_unit[1]]
    
    # Convert distance to meters
    distance_units = {'m': 1, 'cm': 0.01, 'mm': 0.001, 'μm': 1e-6, 'ft': 0.3048}
    r_m = arr_val[2] * distance_units[arr_unit[2]]
    
    # Calculate gravitational force
    G = 6.67e-11  # N⋅kg^-2⋅m^2
    return G * (m1_kg * m2_kg) / (r_m ** 2)