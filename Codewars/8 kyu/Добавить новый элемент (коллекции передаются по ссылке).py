# Добавить элемент в список:

# Метод AddExtra добавляет новый элемент в список и возвращает список. 
# Новым элементом может быть любой объект, это не имеет значения. 
# (Допустим, вы добавляете целое число, например, 13).

# В нашем тестовом примере мы проверяем, чтобы возвращаемый список 
# содержал на один элемент больше, чем входной список. Однако для прохождения этой проверки метод нуждается в некоторой модификации.

# P.S. Вам нужно создать новый список и добавить в него новый элемент. 
# (Это задание изначально разработано для языка C# и показывает, что добавление 
# нового элемента во входной список не сработает, даже если параметр передается 
# по значению, но значение указывает на ссылку на список, и любое изменение параметра будет видно вызывающей стороне).

def add_extra(list_of_numbers):
    new_list = list_of_numbers.copy()  # Создаем копию входного списка
    new_list.append(13)  # Добавляем новый элемент (например, 13)
    return new_list  # Возвращаем новый список