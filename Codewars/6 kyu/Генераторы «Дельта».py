# input = [set([6, 2, 'A']), set([2, 'B', 8]), set(['A', 'B'])]

# delta(input, 1) # [{8, 'B'}, {'A'}]
# delta(input, 2) # [{'A'}]

def delta(values, n):
    if n == 0:
        for v in values:
            yield v
    else:
        prev = None
        for v in delta(values, n-1):
            if prev is not None:
                yield v - prev
            prev = v