# Введение
# В MIDI-файлах метки времени хранятся в виде целых чисел, представляющих количество «тиков» с момента предыдущего события в файле.

# Поскольку эти временные метки являются относительными, большинство значений, как правило, довольно малы. Для экономии места в MIDI-файлах используется специальный формат целочисленного кодирования, называемый форматом переменной длины (VLQ) .

# MIDI VLQ хранит целое число, используя один или несколько байтов:

# Младшие 7 бит каждого байта содержат фактические данные.
# Старший бит указывает, следует ли за ним следующий байт.
# 1означает, что за ним следует еще один байт
# 0Это означает, что это последний байт.
# Например:

# 0x7F -> 01111111
# Поскольку старший бит равен 0, это последний байт.

# Удаление бита продолжения оставляет следующее:

# 1111111 = 127
# Значения больше 127 требуют нескольких байтов.

# Например:

# [0x81, 0x00]
# В двоичном представлении это выглядит так:

# 10000001 00000000
# Удаление битов продолжения дает следующий результат:

# 0000001 0000000
# А именно:

# 00000010000000 = 128
# Так:

# [0x81, 0x00] represents 128
# Задача
# Ваша задача — реализовать две функции:

# encode(n)
# decode(data)
# encodeдолжен преобразовывать целое число в последовательность байтов MIDI VLQ.
# decodeДекодировать следует только первый полный MIDI VLQ-байт, содержащийся во входном сигнале. Любые дополнительные байты после завершающего VLQ-байта следует игнорировать.
# Все тестовые значения будут удовлетворять следующим условиям:

# 0 <= n <= 0x0FFFFFFF

# Какое максимальное значение может быть представлено 4-байтовым MIDI VLQ-сигналом?

# Примеры
# Кодировать:

# encode(0)    == [0x00]
# encode(127)  == [0x7F]
# encode(128)  == [0x81, 0x00]
# encode(8192) == [0xC0, 0x00]
# Расшифровка:

# decode([0x00])                   == 0
# decode([0x7F])                   == 127
# decode([0x81, 0x00])             == 128
# decode([0xFF, 0xFF, 0xFF, 0x7F]) == 268435455

def encode(n: int) -> list[int]:
    if n == 0:
        return [0x00]

    bytes_list = []
    while n > 0:
        byte = n & 0x7F  # Получаем младшие 7 бит
        n >>= 7          # Сдвигаем число на 7 бит вправо
        if bytes_list:   # Если это не первый байт, устанавливаем старший бит
            byte |= 0x80
        bytes_list.append(byte)

    return bytes_list[::-1]  # Возвращаем в правильном порядке

def decode(data: list[int]) -> int:
    n = 0
    for byte in data:
        n <<= 7          # Сдвигаем число на 7 бит влево
        n |= (byte & 0x7F)  # Добавляем младшие 7 бит текущего байта
        if (byte & 0x80) == 0:  # Если старший бит не установлен, это последний байт
            break
    return n