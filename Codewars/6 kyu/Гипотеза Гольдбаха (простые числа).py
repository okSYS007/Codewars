# Гипотеза Гольдбаха — одна из старейших и наиболее известных нерешенных проблем в теории чисел и во всей математике. Она гласит:

# Любое четное целое число больше 2 может быть выражено как сумма двух простых чисел.

# Например:

# 6 = 3 + 3
# 8 = 3 + 5
# 10 = 3 + 7
# 12 = 5 + 7
# Задача
# Напишите функцию, которая принимает четное число и возвращает массив, содержащий все пары простых чисел, сумма которых равна этому числу:

# even_number = 18  # => [[5, 13], [7, 11]] 
# even_number = 34  # => [[3, 31], [5, 29], [11, 23], [17, 17]] 
# Правила:

# В каждой паре сначала следует указать меньшее простое число: например [3, 5], , а не[5, 3]

# Все пары должны быть расположены в порядке возрастания, начиная с первого элемента пары: [[5, 13], [7, 11]]принимается, а [[7, 11], [5, 13]]не принимается.

def goldbach(even_number):
    def is_prime(n):
        if n < 2:
            return False
        for i in range(2, int(n**0.5) + 1):
            if n % i == 0:
                return False
        return True

    primes = [i for i in range(2, even_number) if is_prime(i)]
    pairs = []
    for prime in primes:
        complement = even_number - prime
        if complement >= prime and is_prime(complement):
            pairs.append([prime, complement])
    return pairs

