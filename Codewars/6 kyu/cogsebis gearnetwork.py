# Сложные системы зубчатых передач с блокировкой могут одновременно приводить в движение несколько соседних узлов.

# Ряд зубчатых колес соединен в разветвленную сеть. В отличие от простых зубчатых передач, 
# расположенных по прямой линии, одно зубчатое колесо в этой системе может одновременно приводить
#  в движение множество других зубчатых колес, создавая сложные разветвления и сети механической энергии!

# Вам дан список шестеренок, количество зубьев и перечень физических соединений. Одна из конкретных шестеренок 
# — ведущая , которая вращается с заданной частотой вращения (об/мин). Ваша задача — рассчитать конечную частоту вращения всех шестеренок в сети.

# Правила включения передач
# Передаточное число: Если шестерня А приводит в движение шестерню В, то передаточное число определяется их зубьями. Формула выглядит следующим образом: RPM_B = RPM_A * (Teeth_A / Teeth_B)
# Направление вращения: Каждый раз, когда одна шестерня приводит в движение другую, направление вращения меняется на противоположное.
# Вращение по часовой стрелке обозначается положительным числом оборотов в минуту.
# Вращение против часовой стрелки обозначается отрицательным числом оборотов в минуту.
# Ведущая шестерня: Начальная частота вращения ведущей шестерни всегда указывается положительным числом (по часовой стрелке).
# Допустимые зубчатые передачи: Можно с уверенностью предположить, что все предоставленные зубчатые передачи физически корректны. Они не будут блокироваться или заклинивать (например, отсутствуют невозможные петли или конфликтующие передаточные числа).
# Вход
# gears: Массив целых чисел, где индекс — это идентификатор шестерни, а значение — количество зубьев. (например, [10, 20, 30]означает, что шестерня 0 имеет 10 зубьев, шестерня 1 — 20 зубьев, шестерня 2 — 30 зубьев).
# connections: Массив пар, [A, B]представляющих физическое зацепление между шестерней A и шестерней B.
# driver_id: Целочисленный идентификатор шестерни, обеспечивающей подачу мощности.
# driver_rpmНачальная частота вращения ведущей шестерни (может быть целым числом или плавающей запятой).
# Выход
# Возвращает массив значений оборотов в минуту для всех передач (отсортированных по их идентификатору).

# Округлять окончательные результаты не следует . Возвращайте точные значения с плавающей запятой (в наборе тестов используется нечеткое сопоставление для учета незначительных ошибок точности чисел с плавающей запятой).
# Если шестерня полностью отсоединена от приводной системы, то её обороты в минуту равны 0.0.
# Пример
# const gears = [10, 20, 50, 10];
# const connections = [[0, 1], [1, 2], [1, 3]];
# const driverId = 0;
# const driverRpm = 100.0;

# cogsebi(gears, connections, driverId, driverRpm);
# // Returns: [100.0, -50.0, 20.0, 100.0]
# Если возникла проблема или ошибка, оставьте комментарий.

from collections import deque


def cogsebi(gears, connections, driver_id, driver_rpm):
    graph = [[] for _ in gears]
    for a, b in connections:
        graph[a].append(b)
        graph[b].append(a)

    rpms = [0.0] * len(gears)
    rpms[driver_id] = float(driver_rpm)

    queue = deque([driver_id])
    seen = {driver_id}

    while queue:
        current = queue.popleft()

        for neighbour in graph[current]:
            if neighbour in seen:
                continue

            rpms[neighbour] = -rpms[current] * gears[current] / gears[neighbour]
            seen.add(neighbour)
            queue.append(neighbour)

    return rpms


